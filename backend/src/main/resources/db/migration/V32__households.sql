-- Households (ADR 0038): a family as a unit. Members are devotee records; a devotee belongs to at
-- most one household. The shared address and family gotra live on the household. Erasing a
-- devotee removes their membership (ON DELETE CASCADE; anonymised records: DevoteeService).

CREATE TABLE household (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT      NOT NULL REFERENCES tenant(id),
    name         TEXT        NOT NULL CHECK (length(name) BETWEEN 1 AND 120),
    gotra        TEXT        CHECK (length(gotra) <= 60),
    address_line TEXT        CHECK (length(address_line) <= 200),
    city         TEXT        CHECK (length(city) <= 80),
    state        TEXT        CHECK (length(state) <= 80),
    pincode      TEXT        CHECK (pincode ~ '^[1-9][0-9]{5}$'),
    notes        TEXT        CHECK (length(notes) <= 500),
    created_by   BIGINT      NOT NULL REFERENCES app_user(id),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE household_member (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT      NOT NULL REFERENCES tenant(id),
    household_id BIGINT      NOT NULL REFERENCES household(id) ON DELETE CASCADE,
    devotee_id   BIGINT      NOT NULL UNIQUE REFERENCES devotee(id) ON DELETE CASCADE,
    relation     TEXT        NOT NULL CHECK (relation IN ('HEAD', 'SPOUSE', 'CHILD', 'PARENT', 'SIBLING', 'GRANDPARENT', 'GRANDCHILD', 'OTHER')),
    added_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_household_member_household ON household_member(household_id);
-- One head of the family per household.
CREATE UNIQUE INDEX uq_household_head ON household_member(household_id) WHERE relation = 'HEAD';

ALTER TABLE household ENABLE ROW LEVEL SECURITY;
ALTER TABLE household FORCE  ROW LEVEL SECURITY;
CREATE POLICY household_tenant_isolation ON household
    USING      (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint)
    WITH CHECK (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint);

ALTER TABLE household_member ENABLE ROW LEVEL SECURITY;
ALTER TABLE household_member FORCE  ROW LEVEL SECURITY;
CREATE POLICY household_member_tenant_isolation ON household_member
    USING      (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint)
    WITH CHECK (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint);

