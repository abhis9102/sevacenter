-- Households in My Mandir (ADR 0039): devotees start their family, add their children, and invite
-- adults, who join only by accepting (signed in with the invited phone/email: their own consent).

-- A devotee can now create a devotee record themselves (theirs, or their child's): the actor is
-- their MandirCenter account instead of a staff member. Every record has one or the other.
ALTER TABLE devotee ALTER COLUMN created_by DROP NOT NULL;
ALTER TABLE devotee ALTER COLUMN updated_by DROP NOT NULL;
ALTER TABLE devotee ALTER COLUMN consent_recorded_by DROP NOT NULL;
ALTER TABLE devotee ADD COLUMN created_by_account BIGINT REFERENCES devotee_account(id);
ALTER TABLE devotee ADD COLUMN updated_by_account BIGINT REFERENCES devotee_account(id);
ALTER TABLE devotee ADD CONSTRAINT devotee_creator CHECK (
    (created_by IS NOT NULL AND consent_recorded_by IS NOT NULL) OR created_by_account IS NOT NULL);
ALTER TABLE devotee ADD CONSTRAINT devotee_updater CHECK (updated_by IS NOT NULL OR updated_by_account IS NOT NULL);

-- A devotee can start their own household in My Mandir.
ALTER TABLE household ALTER COLUMN created_by DROP NOT NULL;
ALTER TABLE household ADD COLUMN created_by_account BIGINT REFERENCES devotee_account(id);
ALTER TABLE household ADD CONSTRAINT household_creator CHECK (created_by IS NOT NULL OR created_by_account IS NOT NULL);

-- Who put someone in a household: staff (null here) or a devotee's account.
ALTER TABLE household_member ADD COLUMN added_by_account BIGINT REFERENCES devotee_account(id);

-- An adult invited into a household. Accepted only by an account that verified this exact contact.
CREATE TABLE household_invite (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT      NOT NULL REFERENCES tenant(id),
    household_id BIGINT      NOT NULL REFERENCES household(id) ON DELETE CASCADE,
    channel      TEXT        NOT NULL CHECK (channel IN ('EMAIL', 'SMS')),
    contact      TEXT        NOT NULL CHECK (length(contact) BETWEEN 5 AND 254),
    relation     TEXT        NOT NULL CHECK (relation IN ('SPOUSE', 'PARENT', 'SIBLING', 'GRANDPARENT', 'CHILD', 'GRANDCHILD', 'OTHER')),
    status       TEXT        NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED')),
    invited_by   BIGINT      NOT NULL REFERENCES devotee_account(id),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at   TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_household_invite_contact ON household_invite(tenant_id, contact, status);

ALTER TABLE household_invite ENABLE ROW LEVEL SECURITY;
ALTER TABLE household_invite FORCE  ROW LEVEL SECURITY;
CREATE POLICY household_invite_tenant_isolation ON household_invite
    USING      (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint)
    WITH CHECK (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'sevacenter_app') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON household_invite TO sevacenter_app;
    END IF;
END $$;
