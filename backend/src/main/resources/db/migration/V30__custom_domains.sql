-- MandirCenter on a temple's own domain (ADR 0036). Two tables:
--
--  custom_domain  a trust's claims (RLS): hostname, the secret TXT token that proves ownership,
--                 status. Several trusts may claim the same name; only DNS proof activates one.
--  tenant_domain  the routing registry: verified, active hostname -> tenant, read before any
--                 tenant is known. Anyone may read it (the data is public: it's in DNS), but a
--                 trust can only add or remove its own routes, and the primary key lets exactly
--                 one trust own a hostname.

CREATE TABLE custom_domain (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT      NOT NULL REFERENCES tenant(id),
    hostname        TEXT        NOT NULL CHECK (hostname ~ '^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$'
                                                AND length(hostname) <= 253),
    token           TEXT        NOT NULL CHECK (token ~ '^sc-verify-[A-Za-z0-9_-]{32}$'),
    status          TEXT        NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACTIVE', 'FAILED')),
    points_here     BOOLEAN     NOT NULL DEFAULT false,
    last_error      TEXT        CHECK (length(last_error) <= 200),
    created_by      BIGINT      NOT NULL REFERENCES app_user(id),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    verified_at     TIMESTAMPTZ,
    last_checked_at TIMESTAMPTZ,
    UNIQUE (tenant_id, hostname)
);

ALTER TABLE custom_domain ENABLE ROW LEVEL SECURITY;
ALTER TABLE custom_domain FORCE  ROW LEVEL SECURITY;
CREATE POLICY custom_domain_tenant_isolation ON custom_domain
    USING      (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint)
    WITH CHECK (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint);

CREATE TABLE tenant_domain (
    hostname   TEXT        PRIMARY KEY,
    tenant_id  BIGINT      NOT NULL REFERENCES tenant(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_tenant_domain_tenant ON tenant_domain(tenant_id);

ALTER TABLE tenant_domain ENABLE ROW LEVEL SECURITY;
ALTER TABLE tenant_domain FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_domain_read ON tenant_domain FOR SELECT USING (true);
CREATE POLICY tenant_domain_add ON tenant_domain FOR INSERT
    WITH CHECK (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint);
CREATE POLICY tenant_domain_remove ON tenant_domain FOR DELETE
    USING (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'sevacenter_app') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON custom_domain TO sevacenter_app;
        GRANT SELECT, INSERT, DELETE ON tenant_domain TO sevacenter_app;
    END IF;
END $$;
