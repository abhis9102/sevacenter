-- Groups (ADR 0037): satsang, bhajan mandali, youth, mahila mandal, study circles. Staff run them
-- in SevaCenter; devotees find and join public ones on MandirCenter, signed in with their login
-- code. Devotees see a member count only, never other members.

CREATE TABLE community_group (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT      NOT NULL REFERENCES tenant(id),
    name         TEXT        NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
    description  TEXT        CHECK (length(description) <= 1000),
    category     TEXT        NOT NULL CHECK (category IN ('SATSANG', 'BHAJAN', 'YOUTH', 'WOMEN', 'STUDY', 'SEVA', 'OTHER')),
    meets        TEXT        CHECK (length(meets) <= 200),
    location     TEXT        CHECK (length(location) <= 200),
    capacity     INT         CHECK (capacity BETWEEN 1 AND 10000),
    visibility   TEXT        NOT NULL CHECK (visibility IN ('PUBLIC', 'PRIVATE')),
    join_policy  TEXT        NOT NULL CHECK (join_policy IN ('OPEN', 'APPROVAL')),
    active       BOOLEAN     NOT NULL DEFAULT true,
    created_by   BIGINT      NOT NULL REFERENCES app_user(id),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_community_group_tenant ON community_group(tenant_id, active);

CREATE TABLE group_member (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT      NOT NULL REFERENCES tenant(id),
    group_id     BIGINT      NOT NULL REFERENCES community_group(id) ON DELETE CASCADE,
    account_id   BIGINT      NOT NULL REFERENCES devotee_account(id),
    status       TEXT        NOT NULL CHECK (status IN ('PENDING', 'ACTIVE')),
    added_by     BIGINT      REFERENCES app_user(id), -- staff who added or approved; null = joined themselves
    requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    joined_at    TIMESTAMPTZ,
    UNIQUE (group_id, account_id)
);
CREATE INDEX idx_group_member_account ON group_member(tenant_id, account_id);

ALTER TABLE community_group ENABLE ROW LEVEL SECURITY;
ALTER TABLE community_group FORCE  ROW LEVEL SECURITY;
CREATE POLICY community_group_tenant_isolation ON community_group
    USING      (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint)
    WITH CHECK (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint);

ALTER TABLE group_member ENABLE ROW LEVEL SECURITY;
ALTER TABLE group_member FORCE  ROW LEVEL SECURITY;
CREATE POLICY group_member_tenant_isolation ON group_member
    USING      (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint)
    WITH CHECK (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint);

-- Staff access per module (ADR 0021) gains GROUPS.
ALTER TABLE app_user DROP CONSTRAINT IF EXISTS app_user_module_limits_check;
ALTER TABLE app_user ADD CONSTRAINT app_user_module_limits_check CHECK (module_limits ~
    '^(DEVOTEES|DONATIONS|EVENTS|PUJAS|VOLUNTEERS|TEMPLE|GROUPS):(VIEW|NONE)(,(DEVOTEES|DONATIONS|EVENTS|PUJAS|VOLUNTEERS|TEMPLE|GROUPS):(VIEW|NONE)){0,6}$');

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'sevacenter_app') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON community_group, group_member TO sevacenter_app;
    END IF;
END $$;
