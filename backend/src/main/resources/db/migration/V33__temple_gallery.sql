-- Photos on the MandirCenter About page (About and History sections). Same rules as the temple
-- photo (V29): only images the server re-encoded itself (TempleImageProcessor) are stored.

CREATE TABLE temple_gallery_image (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT      NOT NULL REFERENCES tenant(id),
    section      TEXT        NOT NULL CHECK (section IN ('ABOUT', 'HISTORY')),
    caption      TEXT        CHECK (length(caption) <= 200),
    data         BYTEA       NOT NULL CHECK (octet_length(data) <= 1048576),
    width        INT         NOT NULL CHECK (width BETWEEN 1 AND 1600),
    height       INT         NOT NULL CHECK (height BETWEEN 1 AND 1600),
    version      TEXT        NOT NULL CHECK (version ~ '^[0-9a-f]{16}$'),
    uploaded_by  BIGINT      NOT NULL REFERENCES app_user(id),
    uploaded_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_temple_gallery_tenant ON temple_gallery_image(tenant_id, section, id);

ALTER TABLE temple_gallery_image ENABLE ROW LEVEL SECURITY;
ALTER TABLE temple_gallery_image FORCE  ROW LEVEL SECURITY;
CREATE POLICY temple_gallery_image_tenant_isolation ON temple_gallery_image
    USING      (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint)
    WITH CHECK (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'sevacenter_app') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON temple_gallery_image TO sevacenter_app;
    END IF;
END $$;
