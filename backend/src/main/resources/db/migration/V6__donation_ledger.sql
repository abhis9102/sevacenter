        -- Append-only: no UPDATE, no DELETE. Corrections are reversal rows.
        GRANT SELECT, INSERT ON donation TO sevacenter_app;
        GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO sevacenter_app;
    END IF;
END $$;
